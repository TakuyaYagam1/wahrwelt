def switchwall_source(with_flags: bool) -> str:
    flags = '        MPVPAPER_FLAGS="-p -a max"\n' if with_flags else ""
    flag_use = "$MPVPAPER_FLAGS " if with_flags else ""
    return textwrap.dedent(
        f"""\
        CUSTOM_DIR="$XDG_CONFIG_HOME/hypr/custom"
        RESTORE_SCRIPT_DIR="$CUSTOM_DIR/scripts"
        RESTORE_SCRIPT="$RESTORE_SCRIPT_DIR/__restore_video_wallpaper.sh"
        VIDEO_OPTS="no-audio loop hwdec=auto"
        {flags}
        create_restore_script() {{
            local video_path=$1
            cat > "$RESTORE_SCRIPT.tmp" << EOF
        #!/bin/bash
        # Generated by switchwall.sh - Don't modify it by yourself.
        # Time: $(date)

        pkill -f -9 mpvpaper

        for monitor in \\$(hyprctl monitors -j | jq -r '.[] | .name'); do
            mpvpaper {flag_use}-o "$VIDEO_OPTS" "\\$monitor" "$video_path" &
            sleep 0.1
        done
        EOF
            mv "$RESTORE_SCRIPT.tmp" "$RESTORE_SCRIPT"
            chmod +x "$RESTORE_SCRIPT"
        }}

        remove_restore() {{
            cat > "$RESTORE_SCRIPT.tmp" << EOF
        #!/bin/bash
        # The content of this script will be generated by switchwall.sh - Don't modify it by yourself.
        EOF
            mv "$RESTORE_SCRIPT.tmp" "$RESTORE_SCRIPT"
        }}

        switch_video() {{
            local video_path="$1"
            local monitor=DP-1
            mpvpaper {flag_use}-o "$VIDEO_OPTS" "$monitor" "$video_path" &
        }}
        """
    )


def switchwall_source_with_ipc() -> str:
    return textwrap.dedent(
        """\
        CUSTOM_DIR="$XDG_CONFIG_HOME/hypr/custom"
        RESTORE_SCRIPT_DIR="$CUSTOM_DIR/scripts"
        RESTORE_SCRIPT="$RESTORE_SCRIPT_DIR/__restore_video_wallpaper.sh"
        VIDEO_OPTS="no-audio loop hwdec=auto"
        MPV_SOCKET_DIR="${XDG_RUNTIME_DIR:-/run/user/$(id -u)}"
        MPV_SOCKET_PREFIX="$MPV_SOCKET_DIR/mpvpaper-"
        MPVPAPER_FLAGS="-p -a max"
        create_restore_script() {
            local video_path=$1
            cat > "$RESTORE_SCRIPT.tmp" << EOF
        #!/bin/bash
        rm -f "$MPV_SOCKET_PREFIX"*.sock
        for monitor in \\$(hyprctl monitors -j | jq -r '.[] | .name'); do
            mpvpaper $MPVPAPER_FLAGS -o "$VIDEO_OPTS input-ipc-server=$MPV_SOCKET_PREFIX\\$monitor.sock" "\\$monitor" "$video_path" &
            sleep 0.1
        done
        EOF
            mv "$RESTORE_SCRIPT.tmp" "$RESTORE_SCRIPT"
            chmod +x "$RESTORE_SCRIPT"
        }

        remove_restore() {
            cat > "$RESTORE_SCRIPT.tmp" << EOF
        #!/bin/bash
        EOF
            mv "$RESTORE_SCRIPT.tmp" "$RESTORE_SCRIPT"
        }

        switch_video() {
            local video_path="$1"
            local monitor=DP-1
            rm -f "$MPV_SOCKET_PREFIX"*.sock
            mpvpaper $MPVPAPER_FLAGS -o "$VIDEO_OPTS input-ipc-server=$MPV_SOCKET_PREFIX$monitor.sock" "$monitor" "$video_path" &
        }
        """
    )


class PcSettingsPreviewTest(unittest.TestCase):
    def test_preview_patch_accepts_upstream_indentation_changes(self) -> None:
        patch_preview = getattr(LIVE_WALLPAPERS, "patch_pc_settings_preview", None)
        self.assertIsNotNone(patch_preview, "missing pC settings preview patch helper")

        expression = (
            "source: /\\.(mp4|webm|mkv|avi|mov)$/i.test(Config.options.background.wallpaperPath)\n"
            "    ? Config.options.background.thumbnailPath\n"
            "    : Config.options.background.wallpaperPath"
        )
        replacement = (
            "source: Wallpapers.imageSourceFor(Config.options.background.wallpaperPath)"
        )

        for indentation in (20, 24):
            with self.subTest(indentation=indentation):
                indent = " " * indentation
                source = indent + expression.replace("\n", f"\n{indent}") + "\n"
                expected = indent + replacement + "\n"
                self.assertEqual(patch_preview(source, "QuickConfig fixture"), expected)


class PcSidebarBannerTest(unittest.TestCase):
    def test_banner_patch_accepts_upstream_indentation_changes(self) -> None:
        for indentation in (32, 36):
            with self.subTest(indentation=indentation):
                indent = " " * indentation
                source = (
                    f'{indent}source: Config.options.sidebar.bannerImage !== "" \n'
                    f"{indent}    ? Config.options.sidebar.bannerImage \n"
                    f"{indent}    : Config.options.background.wallpaperPath\n"
                )
                expected = source.replace(
                    ": Config.options.background.wallpaperPath",
                    ": Wallpapers.imageSourceFor(Config.options.background.wallpaperPath)",
                )
                self.assertEqual(
                    LIVE_WALLPAPERS.patch_pc_sidebar_banner(source, "Sidebar fixture"),
                    expected,
                )

    def test_banner_patch_rejects_missing_or_ambiguous_expression(self) -> None:
        expression = (
            'source: Config.options.sidebar.bannerImage !== ""\n'
            "    ? Config.options.sidebar.bannerImage\n"
            "    : Config.options.background.wallpaperPath\n"
        )
        for source in (expression.replace("!==", "==="), expression * 2):
            with (
                self.subTest(source=source),
                self.assertRaisesRegex(SystemExit, "expected 1 matches"),
            ):
                LIVE_WALLPAPERS.patch_pc_sidebar_banner(source, "Sidebar fixture")


class WallpaperServiceDriftTest(unittest.TestCase):
    def test_unreviewed_service_is_rejected_without_replacing_it(self) -> None:
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            path = root / "services/Wallpapers.qml"
            path.parent.mkdir()
            original = "pragma Singleton\nFolderListModelWithHistory\nproperty string searchQuery\n"
            path.write_text(original)
            with self.assertRaisesRegex(SystemExit, "upstream Wallpapers.qml drifted"):
                LIVE_WALLPAPERS.patch_service(root, "pc")
            self.assertEqual(path.read_text(), original)


class GeminiCategorizerTest(unittest.TestCase):
    OLD_RESIZE = """RESIZED_IMG_PATH="/tmp/quickshell/ai/wallpaper.jpg"

# Resize image for speed
mkdir -p "$(dirname "$RESIZED_IMG_PATH")"
magick "$SOURCE_IMG_PATH" -resize 200x -quality 50 "$RESIZED_IMG_PATH"
"""
    PC_VIDEO_RESIZE = """RESIZED_IMG_PATH="/tmp/quickshell/ai/wallpaper.jpg"

# Resize image for speed
mkdir -p "$(dirname "$RESIZED_IMG_PATH")"
case "${SOURCE_IMG_PATH,,}" in
    *.mp4|*.webm|*.mkv|*.avi|*.mov)
        ffmpeg -y -loglevel error -i "$SOURCE_IMG_PATH" -frames:v 1 -vf scale=200:-2 -q:v 10 "$RESIZED_IMG_PATH"
        ;;
    *)
        magick "$SOURCE_IMG_PATH[0]" -resize 200x -quality 50 "$RESIZED_IMG_PATH"
        ;;
esac
"""

    def test_pc_categorizer_is_left_to_upstream(self) -> None:
        for source in (self.OLD_RESIZE, self.PC_VIDEO_RESIZE):
            with (
                self.subTest(native_video=source == self.PC_VIDEO_RESIZE),
                tempfile.TemporaryDirectory() as directory,
            ):
                root = Path(directory)
                path = root / "scripts/ai/gemini-categorize-wallpaper.sh"
                path.parent.mkdir(parents=True)
                path.write_text(source)

                LIVE_WALLPAPERS.patch_gemini_categorizer(root)

                self.assertEqual(path.read_text(), source)

    def test_official_categorizer_still_handles_video(self) -> None:
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            path = root / "ii/scripts/ai/gemini-categorize-wallpaper.sh"
            path.parent.mkdir(parents=True)
            path.write_text(self.OLD_RESIZE)

            LIVE_WALLPAPERS.patch_gemini_categorizer(root)

            patched = path.read_text()
            self.assertIn("ffmpeg -nostdin -loglevel error", patched)
            self.assertIn("trap cleanup EXIT", patched)
            self.assertNotIn(self.OLD_RESIZE, patched)


class SwitchwallPatchTest(unittest.TestCase):
    def make_restore(
        self, source: str, video_path: str, runtime_dir: Path | None = None
    ) -> tuple[list[str], list[str], str]:
        patch_switchwall = getattr(LIVE_WALLPAPERS, "patch_switchwall", None)
        self.assertIsNotNone(patch_switchwall, "missing switchwall transformation")

        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            script = root / "scripts/colors/switchwall.sh"
            script.parent.mkdir(parents=True)
            script.write_text(source)
            patch_switchwall(root)

            config = root / "config"
            restore_dir = config / "hypr/custom/scripts"
            restore_dir.mkdir(parents=True)
            bin_dir = root / "bin"
            bin_dir.mkdir()
            log = root / "mpvpaper.args"
            runtime_log = root / "mpvpaper.runtime.args"
            stubs = {
                "pkill": "#!/bin/sh\nexit 0\n",
                "hyprctl": "#!/bin/sh\nexit 0\n",
                "jq": "#!/bin/sh\nprintf 'DP-1\\n'\n",
                "sleep": "#!/bin/sh\nexit 0\n",
                "mpvpaper": '#!/bin/sh\nprintf \'%s\\0\' "$@" >> "$MPVPAPER_LOG"\n',
            }
            for name, contents in stubs.items():
                stub = bin_dir / name
                stub.write_text(contents)
                stub.chmod(0o755)
            env = os.environ.copy()
            env["XDG_CONFIG_HOME"] = str(config)
            if runtime_dir is not None:
                env["XDG_RUNTIME_DIR"] = str(runtime_dir)
            env["PATH"] = f"{bin_dir}:{env['PATH']}"
            env["MPVPAPER_LOG"] = str(log)
            generated = subprocess.run(
                [
                    "bash",
                    "-c",
                    'set -e; source "$1"; create_restore_script "$2"',
                    "switchwall-test",
                    str(script),
                    video_path,
                ],
                check=False,
                capture_output=True,
                text=True,
                env=env,
            )
            self.assertEqual(generated.returncode, 0, generated.stderr)
            self.assertEqual(generated.stderr, "")

            restore = restore_dir / "__restore_video_wallpaper.sh"
            self.assertTrue(restore.is_file())
            shebang = restore.read_text().splitlines()[0]
            self.assertTrue(shebang.startswith("#!/"), shebang)
            self.assertTrue(Path(shebang[2:]).is_absolute(), shebang)
            self.assertEqual(Path(shebang[2:]).name, "bash")
            self.assertEqual(
                subprocess.run(["bash", "-n", str(restore)], check=False).returncode,
                0,
            )
            self.assertEqual(generated.stderr, "")

            playback = subprocess.run(
                ["bash", str(restore)],
                check=False,
                capture_output=True,
                text=True,
                env=env,
            )
            self.assertEqual(playback.returncode, 0, playback.stderr)
            self.assertEqual(playback.stderr, "")
            args = log.read_bytes().decode().rstrip("\0").split("\0")
            restore_text = restore.read_text()
            if runtime_dir is not None:
                socket_path = runtime_dir / "mpvpaper-DP-1.sock"
                self.assertFalse(
                    socket_path.exists(), "restore did not clear its IPC socket"
                )
                socket_path.touch()

            runtime_env = env.copy()
            runtime_env["MPVPAPER_LOG"] = str(runtime_log)
            runtime_playback = subprocess.run(
                [
                    "bash",
                    "-c",
                    'set -e; source "$1"; switch_video "$2"',
                    "switchwall-test",
                    str(script),
                    video_path,
                ],
                check=False,
                capture_output=True,
                text=True,
                env=runtime_env,
            )
            self.assertEqual(runtime_playback.returncode, 0, runtime_playback.stderr)
            self.assertEqual(runtime_playback.stderr, "")
            runtime_args = runtime_log.read_bytes().decode().rstrip("\0").split("\0")
            if runtime_dir is not None:
                self.assertFalse(
                    socket_path.exists(), "runtime switch did not clear its IPC socket"
                )

            cleared = subprocess.run(
                [
                    "bash",
                    "-c",
                    'set -e; source "$1"; remove_restore',
                    "switchwall-test",
                    str(script),
                ],
                check=False,
                capture_output=True,
                text=True,
                env=env,
            )
            self.assertEqual(cleared.returncode, 0, cleared.stderr)
            clear_shebang = restore.read_text().splitlines()[0]
            self.assertTrue(clear_shebang.startswith("#!/"), clear_shebang)
            self.assertTrue(Path(clear_shebang[2:]).is_absolute(), clear_shebang)
            self.assertEqual(Path(clear_shebang[2:]).name, "bash")
            return args, runtime_args, restore_text

    def test_old_source_quotes_paths_and_keeps_legacy_playback_args(self) -> None:
        with tempfile.TemporaryDirectory() as directory:
            marker = Path(directory) / "unexpected"
            video_path = f"wallpaper 'quoted' $(touch {marker}).mp4"
            args, _, restore_text = self.make_restore(
                switchwall_source(False), video_path
            )

            self.assertEqual(
                args,
                ["-o", "no-audio loop hwdec=auto", "DP-1", video_path],
            )
            self.assertFalse(marker.exists())
            self.assertTrue(restore_text.splitlines()[0].startswith("#!/"))

    def test_new_source_preserves_mpvpaper_flags_in_generated_playback(self) -> None:
        video_path = "/home/user/Wallpapers/slow dance.mp4"
        args, _, _ = self.make_restore(switchwall_source(True), video_path)

        self.assertEqual(
            args,
            ["-p", "-a", "max", "-o", "no-audio loop hwdec=auto", "DP-1", video_path],
        )

    def test_new_source_accepts_spacing_changes(self) -> None:
        source = switchwall_source(True).replace(
            "mpvpaper $MPVPAPER_FLAGS -o",
            "mpvpaper  $MPVPAPER_FLAGS   -o",
        )
        args, _, _ = self.make_restore(source, "/home/user/Wallpapers/slow dance.mp4")

        self.assertEqual(
            args[:5], ["-p", "-a", "max", "-o", "no-audio loop hwdec=auto"]
        )

    def test_current_upstream_ipc_shape_keeps_socket_and_argv_safe(self) -> None:
        with tempfile.TemporaryDirectory() as directory:
            runtime_dir = Path(directory)
            socket_path = runtime_dir / "mpvpaper-DP-1.sock"
            socket_path.touch()
            unrelated_socket = runtime_dir / "nested" / "mpvpaper-DP-1.sock"
            unrelated_socket.parent.mkdir()
            unrelated_socket.touch()
            marker = runtime_dir / "unexpected"
            video_path = f"wallpaper 'quoted' $(touch {marker}).mp4"

            try:
                restore_args, runtime_args, restore_text = self.make_restore(
                    switchwall_source_with_ipc(), video_path, runtime_dir
                )
            except SystemExit as error:
                self.fail(f"IPC playback source was rejected: {error}")

            self.assertEqual(
                restore_args,
                [
                    "-p",
                    "-a",
                    "max",
                    "-o",
                    f"no-audio loop hwdec=auto input-ipc-server={runtime_dir}/mpvpaper-DP-1.sock",
                    "DP-1",
                    video_path,
                ],
            )
            self.assertEqual(runtime_args, restore_args)
            self.assertIn(
                f"input-ipc-server={runtime_dir}/mpvpaper-$monitor.sock", restore_text
            )
            self.assertFalse(socket_path.exists())
            self.assertTrue(unrelated_socket.exists())
            self.assertFalse(marker.exists())

    def test_dynamic_or_inconsistent_mpvpaper_flags_are_rejected(self) -> None:
        source = switchwall_source(True)
        ipc_source = switchwall_source_with_ipc()
        runtime_ipc_call = (
            'mpvpaper $MPVPAPER_FLAGS -o "$VIDEO_OPTS '
            'input-ipc-server=$MPV_SOCKET_PREFIX$monitor.sock" '
            '"$monitor" "$video_path" &'
        )
        invalid_sources = (
            source.replace('MPVPAPER_FLAGS="-p -a max"', 'MPVPAPER_FLAGS="$(unsafe)"'),
            source.replace("mpvpaper $MPVPAPER_FLAGS -o", "mpvpaper -o", 1),
            source + '\nMPVPAPER_FLAGS="-p -a max"\n',
            source.replace("create_restore_script()", "create_restore_file()"),
            source
            + '\nmpvpaper $MPVPAPER_FLAGS -o \\"$VIDEO_OPTS\\" \\"$monitor\\" \\"$video_path\\" &\n',
            ipc_source.replace(
                runtime_ipc_call,
                'mpvpaper $MPVPAPER_FLAGS -o "$VIDEO_OPTS" "$monitor" "$video_path" &',
                1,
            ),
            ipc_source.replace(
                "input-ipc-server=$MPV_SOCKET_PREFIX\\$monitor.sock",
                "input-ipc-server=$MPV_SOCKET_PREFIX$monitor.sock",
                1,
            ),
            ipc_source.replace(
                'MPV_SOCKET_PREFIX="$MPV_SOCKET_DIR/mpvpaper-"',
                'MPV_SOCKET_PREFIX="$MPV_SOCKET_DIR/unsupported-"',
            ),
            ipc_source.replace('rm -f "$MPV_SOCKET_PREFIX"*.sock\n', "", 1),
            ipc_source.replace(
                "input-ipc-server=$MPV_SOCKET_PREFIX\\$monitor.sock",
                "input-ipc-server=$MPV_SOCKET_PREFIX\\$monitor.sock,unsupported=yes",
                1,
            ),
            ipc_source.replace('MPVPAPER_FLAGS="-p -a max"\n', "").replace(
                "$MPVPAPER_FLAGS ", ""
            ),
        )
        for invalid in invalid_sources:
            with (
                self.subTest(source=invalid[:80]),
                tempfile.TemporaryDirectory() as directory,
            ):
                root = Path(directory)
                script = root / "scripts/colors/switchwall.sh"
                script.parent.mkdir(parents=True)
                script.write_text(invalid)

                with self.assertRaisesRegex(SystemExit, "switchwall"):
                    LIVE_WALLPAPERS.patch_switchwall(root)

                self.assertEqual(script.read_text(), invalid)


